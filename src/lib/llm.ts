import OpenAI from "openai";

const client = new OpenAI({
  apiKey: process.env.GROQ_API_KEY,
  baseURL: "https://api.groq.com/openai/v1",
});

export async function extractContext(rawText: string) {
  const response = await client.chat.completions.create({
    model: "openai/gpt-oss-20b",
    messages: [
      {
        role: "system",
         content: `You are a context extraction engine. Extract information from the voice note into a strict JSON format.
Return ONLY valid JSON. No markdown, no code blocks, no explanations.
The JSON must have exactly these keys:
- "project": (string) The name of the project or feature. Must be 2 to 5 words maximum. If the note is clearly not about software development or work, set project to "NONE".
- "status": (string) Current status of the work. One sentence, specific and technical. Describe what is happening, not a single-word label. Example: "Investigating 401 on token refresh, ruled out expiry" not "Blocked".
- "tried": (string or null) Past-tense actions. Pay attention to past-tense verbs (checked, tried, ruled out, finished) — these indicate completed work. If none, use null.
- "nextAction": (string or null) One actionable sentence. If no explicit next action is stated, and the note is vague, set to null. Do not invent actions.
- "blockers": (string or null) Named person or dependency. If the note says "no blockers" or doesn't mention being blocked, set to null.
- "tags": (string) exactly 3 to 5 relevant tags, comma-separated, single words or short phrases. Never more than 5.`
      },
      {
        role: "user",
        content: `Voice note: "${rawText}"`,
      },
    ],
    temperature: 0.1,
  });

  const text = response.choices[0]?.message?.content || "{}";
  
  // Clean up in case the LLM adds markdown code blocks anyway
  const cleanJson = text.replace(/```json|```/g, "").trim();
  
  try {
    return JSON.parse(cleanJson);
  } catch (error) {
    console.error("Failed to parse JSON:", text);
    return {};
  }
}

export async function matchContext(query: string, cards: any[]) {
  const cardSummaries = cards
    .map(
      (c) =>
        `ID: ${c.id} | Project: ${c.project} | Status: ${c.status} | Next: ${c.nextAction} | Tags: ${c.tags}`
    )
    .join("\n");

  const response = await client.chat.completions.create({
    model: "openai/gpt-oss-20b",
    messages: [
      {
        role: "system",
        content: `You are a matching engine. Given a user's query and a list of context cards, return the ID of the single most relevant card. Return ONLY the ID string, or "NONE" if no card is relevant. Do not include any other text.`
      },
      {
        role: "user",
        content: `User query: "${query}"
Available cards:
${cardSummaries}`
      },
    ],
    temperature: 0.1,
  });

  return response.choices[0]?.message?.content?.trim() || "NONE";
}

export async function generateBriefing(card: any) {
  const response = await client.chat.completions.create({
    model: "openai/gpt-oss-20b",
    messages: [
      {
        role: "system",
        content: `You are a helpful assistant. Generate a short, encouraging briefing to help a developer resume their work based on the context card provided. Keep it under 3 sentences.`
      },
      {
        role: "user",
        content: `Context Card:
- Project: ${card.project}
- Status: ${card.status}
- Tried: ${card.tried || "N/A"}
- Next Action: ${card.nextAction}
- Blockers: ${card.blockers || "None"}
- Tags: ${card.tags}
- Created: ${card.createdAt}`
      },
    ],
    temperature: 0.3,
  });

  return response.choices[0]?.message?.content || "";
}

export function formatForSlack(card: any): string {
  const lines = [
    `Handoff: ${card.project}`,
    "",
    `Status: ${card.status}`,
  ];
  if (card.tried) lines.push(`Tried: ${card.tried}`);
  lines.push(`Next Action: ${card.nextAction}`);
  if (card.blockers) lines.push(`Blockers: ${card.blockers}`);
  lines.push("");
  lines.push(`Tags: ${card.tags}`);
  lines.push(`Saved: ${new Date(card.createdAt).toLocaleString()}`);
  lines.push("Generated by Context Keeper");
  return lines.join("\n");
}